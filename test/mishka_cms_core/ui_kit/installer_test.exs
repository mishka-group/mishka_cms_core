    test "variants: filter narrows helpers to matching first-positional clauses" do
      {:ok, _} =
        Installer.install_chelekom!(
          bundle_path: @seed_path,
          selection: %{components: ["sample-button"], variants: ["default"]}
        )

      [button] = installed_components() |> Enum.filter(&(&1.name == "kit-sample-button"))

      # color_variant clauses keep ONLY ones whose first arg is "default" or "_".
      cv_clauses = Enum.filter(button.helpers || [], &(&1.name == "color_variant"))
      args_kept = Enum.map(cv_clauses, & &1.args)

      refute Enum.any?(args_kept, &(&1 =~ "\"shadow\""))
      refute Enum.any?(args_kept, &(&1 =~ "\"outline\""))
      assert Enum.any?(args_kept, &(&1 == "_, _")), "catch-all must be retained"
    end

    test "colors: filter narrows helpers to matching second-positional clauses" do
      {:ok, _} =
        Installer.install_chelekom!(
          bundle_path: @seed_path,
          selection: %{components: ["sample-button"], colors: ["primary"]}
        )

      [button] = installed_components() |> Enum.filter(&(&1.name == "kit-sample-button"))
      cv_clauses = Enum.filter(button.helpers || [], &(&1.name == "color_variant"))
      args_kept = Enum.map(cv_clauses, & &1.args)

      refute Enum.any?(args_kept, &(&1 =~ "\"danger\""))
      refute Enum.any?(args_kept, &(&1 =~ "\"success\""))
      assert Enum.any?(args_kept, &(&1 == "_, _"))
    end

    test "per_component overrides take precedence over top-level filters" do
      {:ok, _} =
        Installer.install_chelekom!(
          bundle_path: @seed_path,
          selection: %{
            components: ["sample-button", "sample-card"],
            variants: ["default"],
            per_component: %{
              # card has no `variant` axis — its rounded_class helpers
              # gate on the `rounded` axis. Use the per-component
              # override to filter on that axis directly.
              "sample-card" => %{rounded: ["small"]}
            }
          }
        )

      cards = installed_components() |> Enum.filter(&(&1.name == "kit-sample-card"))
      [card] = cards

      rounded =
        (card.helpers || [])
        |> Enum.filter(&(&1.name == "rounded_class"))
        |> Enum.map(& &1.args)

      refute "\"large\"" in rounded
      assert "_" in rounded, "catch-all rounded_class must remain"
    end

    test "narrow_attr_values is a no-op when the attr has no values: constraint" do
      # Fixture's `variant` attr ships with `opts: {default: "default"}`
      # — no `values:` list to narrow. The selection install must
      # succeed without crashing on the missing key.
      {:ok, _} =
        Installer.install_chelekom!(
          bundle_path: @seed_path,
          selection: %{components: ["sample-button"], variants: ["default"]}
        )

      [button] = installed_components() |> Enum.filter(&(&1.name == "kit-sample-button"))
      variant_attr = Enum.find(button.attrs, &(&1.name == "variant"))

      # Either the original opts map (no values key) or an unmodified
      # passthrough — both prove the narrow function didn't corrupt
      # the attr when there was nothing to narrow.
      assert is_map(variant_attr.opts)
      refute Map.has_key?(variant_attr.opts || %{}, "values")
    end

    test "non-literal helper args (e.g. `assigns`) are always retained" do
      {:ok, _} =
        Installer.install_chelekom!(
          bundle_path: @seed_path,
          selection: %{components: ["sample-button"], variants: ["default"]}
        )

      [button] = installed_components() |> Enum.filter(&(&1.name == "kit-sample-button"))

      # `sample_button_indicator` has args `"assigns"` — non-literal,
      # un-classifiable. Must be kept regardless of selection.
      assert Enum.any?(button.helpers || [], &(&1.name == "sample_button_indicator"))
    end
  end

  ## ─── discriminators ───────────────────────────────────────────────

  describe "install_chelekom!/1 — discriminators" do
    test "every helper carries a discriminators list (possibly empty)" do
      {:ok, _} = Installer.install_chelekom!(bundle_path: @seed_path)

      [button] = installed_components() |> Enum.filter(&(&1.name == "kit-sample-button"))

      Enum.each(button.helpers || [], fn h ->
        assert is_list(h.discriminators), "helper #{h.name}(#{h.args}) lost discriminators"
      end)
    end

    test "AND of two axes: both must intersect the selection" do
      # color_variant("default", "primary") has discriminators
      # [{variant, [default]}, {color, [primary]}].
      # Selection variants=[default], colors=[danger] → variant
      # clause passes (default ∈ default), color clause fails
      # (primary ∉ danger) → helper dropped.
      {:ok, _} =
        Installer.install_chelekom!(
          bundle_path: @seed_path,
          selection: %{
            components: ["sample-button"],
            variants: ["default"],
            colors: ["danger"]
          }
        )

      [button] = installed_components() |> Enum.filter(&(&1.name == "kit-sample-button"))
      cv = Enum.filter(button.helpers || [], &(&1.name == "color_variant"))
      args = Enum.map(cv, & &1.args)

      assert "\"default\", \"danger\"" in args
      refute "\"default\", \"primary\"" in args
      refute "\"outline\", \"primary\"" in args
      assert "_, _" in args, "catch-all (empty discriminators) always retained"
    end

    test "axis not in selection is unconstrained" do
      # variants=[default] alone leaves the color axis unconstrained,
      # so default-paired clauses across all colors stay.
      {:ok, _} =
        Installer.install_chelekom!(
          bundle_path: @seed_path,
          selection: %{components: ["sample-button"], variants: ["default"]}
        )

      [button] = installed_components() |> Enum.filter(&(&1.name == "kit-sample-button"))
      cv = Enum.filter(button.helpers || [], &(&1.name == "color_variant"))
      args = Enum.map(cv, & &1.args)

      assert "\"default\", \"primary\"" in args
      assert "\"default\", \"danger\"" in args
      refute "\"outline\", \"primary\"" in args
    end

    test "empty discriminators ⇒ helper kept under any selection" do
      # `sample_button_indicator(assigns)` has no wrapping `if`,
      # so its discriminators list is `[]`. A maximally restrictive
      # selection must still keep it.
      {:ok, _} =
        Installer.install_chelekom!(
          bundle_path: @seed_path,
          selection: %{
            components: ["sample-button"],
            variants: ["__nothing__"],
            colors: ["__nothing__"]
          }
        )

      [button] = installed_components() |> Enum.filter(&(&1.name == "kit-sample-button"))
      assert Enum.any?(button.helpers || [], &(&1.name == "sample_button_indicator"))
    end
  end

