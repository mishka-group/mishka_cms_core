    test "uninstall_kit!/2 removes the kit by path" do
      {:ok, _} = Installer.install_kit!(@seed_path)
      assert length(installed_components()) == 4

      :ok = Installer.uninstall_kit!(@seed_path)
      assert installed_components() == []
