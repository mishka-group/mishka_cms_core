  end

  describe "list_features/1" do
    test "exposes axes derived from helper discriminators" do
      {:ok, info} = Installer.list_features(bundle_path: @seed_path, component: "sample-button")

      assert info.component == "kit-sample-button"
      # color_variant clauses span variant=[default,outline] × color=[primary,danger]
      assert "default" in info.features["variant"]
      assert "outline" in info.features["variant"]
      assert "primary" in info.features["color"]
      assert "danger" in info.features["color"]
    end

    test "accepts both bare and prefixed component names" do
      assert {:ok, _} = Installer.list_features(bundle_path: @seed_path, component: "sample-card")

      assert {:ok, _} =
               Installer.list_features(bundle_path: @seed_path, component: "kit-sample-card")
    end

