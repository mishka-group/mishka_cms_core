        Installer.install_chelekom!(
          bundle_path: @seed_path,
          selection: %{components: ["kit-sample-button"]}
        )

      assert length(cps) == 1

      names = installed_components() |> Enum.map(& &1.name)
      assert names == ["kit-sample-button"]
