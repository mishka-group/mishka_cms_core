defmodule MishkaCmsCore.UiKit.InstallerTest do
  @moduledoc """
  Integration tests for the v3 thin installer.

  Uses a real Postgres-backed Ash transaction. The fixture
  `test/fixtures/cms_v3_seed.json` was generated by running the
  Chelekom-side `CmsBundleExporter` against `sample_button` and
  `sample_card` (4 components total).
  """

  use MishkaCmsCore.DataCase, async: false
  alias MishkaCmsCore.Runtime.Handlers.UiKitHandler, as: Installer
  alias MishkaCmsCore.Runtime.Component
  require Ash.Query

  @moduletag :integration

  @seed_path Path.expand("../../fixtures/cms_v3_seed.json", __DIR__)

  setup do
    # Best-effort cleanup before each test so they're isolated.
    Installer.uninstall_chelekom!(bundle_path: @seed_path, kit_name: "kit")
    on_exit(fn -> Installer.uninstall_chelekom!(bundle_path: @seed_path, kit_name: "kit") end)
    :ok
  end

  defp installed_components do
    Component
    |> Ash.Query.filter(like(name, "kit-%"))
    |> Ash.read!(authorize?: false)
  end

  ## ─── basic install ─────────────────────────────────────────────────

  describe "install_chelekom!/1" do
    test "creates one Component row per JSON entry" do
      {:ok, %{components: cps}} = Installer.install_chelekom!(bundle_path: @seed_path)

      assert length(cps) == 4

      names = installed_components() |> Enum.map(& &1.name) |> Enum.sort()

      assert names == [
               "kit-sample-button",
               "kit-sample-button-link",
               "kit-sample-card",
               "kit-sample-card-title"
             ]
    end

    test "row attrs come straight from the JSON entry" do
      {:ok, _} = Installer.install_chelekom!(bundle_path: @seed_path)

      btn =
        Component
        |> Ash.Query.filter(name == "kit-sample-button")
        |> Ash.read!(authorize?: false)
        |> hd()

      assert btn.format == :heex
      assert btn.active == true
      assert is_list(btn.helpers)
      assert length(btn.helpers) > 0
      assert is_list(btn.attrs)
      assert btn.extra["ui_kit"] == "kit"
      assert btn.extra["component"] == "sample_button"
      assert btn.extra["function"] == "sample_button"
    end

    test "site_id passes through (nil = global)" do
      {:ok, _} = Installer.install_chelekom!(bundle_path: @seed_path)
      Enum.each(installed_components(), fn c -> assert c.site_id == nil end)
    end

    test "site_id passthrough — tenant install" do
      site_id = ensure_site_for_test()
      {:ok, _} = Installer.install_chelekom!(bundle_path: @seed_path, site_id: site_id)

      Enum.each(installed_components(), fn c ->
        assert c.site_id == site_id
      end)
    end
  end

  ## ─── idempotency ───────────────────────────────────────────────────

  describe "install_chelekom!/1 — idempotency (upsert)" do
    test "re-running install upserts in place — same IDs, no duplicates" do
      {:ok, _} = Installer.install_chelekom!(bundle_path: @seed_path)
      first_ids = installed_components() |> Enum.map(& &1.id) |> Enum.sort()

      # default cleanup: false now → upsert by unique_name_per_site.
      {:ok, _} = Installer.install_chelekom!(bundle_path: @seed_path)
      second = installed_components()
      second_ids = second |> Enum.map(& &1.id) |> Enum.sort()

      assert length(first_ids) == 4
      assert length(second) == 4, "no duplicate rows created on re-import"
      assert first_ids == second_ids, "rows updated in place, IDs preserved"
    end

    test "cleanup: false (default) does NOT crash on re-import — it upserts" do
      {:ok, _} = Installer.install_chelekom!(bundle_path: @seed_path)

      assert {:ok, %{components: cps}} =
               Installer.install_chelekom!(bundle_path: @seed_path, cleanup: false)

      assert length(cps) == 4
      assert length(installed_components()) == 4
    end

    test "cleanup: true wipes prior + recreates (new IDs)" do
      {:ok, _} = Installer.install_chelekom!(bundle_path: @seed_path)
      first_ids = installed_components() |> Enum.map(& &1.id) |> MapSet.new()

      {:ok, _} = Installer.install_chelekom!(bundle_path: @seed_path, cleanup: true)
      second_ids = installed_components() |> Enum.map(& &1.id) |> MapSet.new()

      assert MapSet.size(first_ids) == 4
      assert MapSet.size(second_ids) == 4
      assert MapSet.disjoint?(first_ids, second_ids), "cleanup: true hard-deletes then recreates"
    end

    test "upsert updates content of an existing row (template change reflected)" do
      {:ok, _} = Installer.install_chelekom!(bundle_path: @seed_path)

      [btn] = installed_components() |> Enum.filter(&(&1.name == "kit-sample-button"))
      original_id = btn.id

      # Mutate the row out-of-band, then re-import: upsert must restore the
      # bundle's template (proving it UPDATES, not just ignores existing).
      Component
      |> Ash.Query.filter(id == ^original_id)
      |> Ash.read_one!(authorize?: false)
      |> Ash.Changeset.for_update(:master_update, %{template: "<div>STALE</div>"},
        authorize?: false
      )
      |> Ash.update!(authorize?: false)

      {:ok, _} = Installer.install_chelekom!(bundle_path: @seed_path)

      [btn2] = installed_components() |> Enum.filter(&(&1.name == "kit-sample-button"))
      assert btn2.id == original_id, "same row (upsert), not a new one"
      refute btn2.template == "<div>STALE</div>", "template restored from bundle by upsert"
    end
  end

  describe "install_chelekom!/1 — archived rows are skipped" do
    test "an archived row is NOT resurrected and is reported in skipped_archived" do
      {:ok, _} = Installer.install_chelekom!(bundle_path: @seed_path)
      [btn] = installed_components() |> Enum.filter(&(&1.name == "kit-sample-button"))

      # Soft-delete (archive) the button — AshArchival sets archived_at.
      Ash.destroy!(btn, action: :master_destroy, authorize?: false)
      refute Enum.any?(installed_components(), &(&1.name == "kit-sample-button"))

      {:ok, result} = Installer.install_chelekom!(bundle_path: @seed_path)

      # Reported as skipped, NOT recreated as a new active row.
      assert "kit-sample-button" in result.skipped_archived.components

      refute Enum.any?(installed_components(), &(&1.name == "kit-sample-button")),
             "archived row must not be resurrected; admin must unarchive first"

      # The other three still upsert normally.
      assert length(result.components) == 3
    end

    test "skipped_archived is empty on a clean install" do
      {:ok, result} = Installer.install_chelekom!(bundle_path: @seed_path)

      assert result.skipped_archived == %{components: [], js_hooks: [], stylesheets: []}
      assert length(result.components) == 4
    end
  end

  describe "install_kit!/2 — generic API" do
    test "install_kit!/2 installs from an explicit bundle path" do
      {:ok, %{components: cps}} = Installer.install_kit!(@seed_path)
      assert length(cps) == 4
      assert length(installed_components()) == 4
    end

