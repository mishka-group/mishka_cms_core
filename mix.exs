defmodule MishkaCmsCore.MixProject do
  use Mix.Project

  def project do
    [
      app: :mishka_cms_core,
      version: "0.0.1",
      elixir: "~> 1.18",
      start_permanent: Mix.env() == :prod,
      deps: deps(),
      consolidate_protocols: Mix.env() != :dev,
      aliases: aliases(),
      elixirc_paths: elixirc_paths(Mix.env()),
      package: package(),
      gettext: [excluded_refs_from_purging: ~r{^\.\./mishka_gervaz/}]
    ]
  end

  # `priv/cms_ui_kits` and `priv/dev_seed_media` ship: both are real content read through
  # `:code.priv_dir/1` at runtime — the Chelekom bundle the UI-kit installer reads, and the pictures
  # `MishkaCmsCore.Dev.SeedMedia` puts in a seeded media library — and `lib` carries the code that
  # reads them, so leaving either out ships half of a working thing. The rest of `priv` does NOT —
  # `priv/repo/migrations` and `priv/resource_snapshots` are generated by `mix ash.codegen` for the
  # standalone test database and describe tables a host owns. `config` and `test` are absent because
  # they exist only to run the suite on its own.
  defp package do
    [
      files: ~w(lib priv/cms_ui_kits priv/dev_seed_media .formatter.exs mix.exs LICENSE README*)
    ]
  end

  # Run "mix help compile.app" to learn about applications.
  def application do
    [
      extra_applications: [:logger],
      mod: {MishkaCmsCore.Application, []}
    ]
  end

