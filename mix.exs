defmodule MishkaCmsCore.MixProject do
  use Mix.Project

  def project do
    [
      app: :mishka_cms_core,
      version: "0.0.1",
      elixir: "~> 1.18",
      start_permanent: Mix.env() == :prod,
      deps: deps(),
      consolidate_protocols: Mix.env() != :dev,
      aliases: aliases(),
      elixirc_paths: elixirc_paths(Mix.env()),
      package: package(),
      # A reference outside the core is written by `mix mishka_cms_core.gettext.gervaz` or
      # `mix mishka_cms_core.gettext.extensions`; `mix gettext.extract` keeps its message.
      gettext: [excluded_refs_from_purging: ~r{^\.\./}]
    ]
  end

  # `priv/cms_ui_kits`, `priv/dev_seed_media` and `priv/share_card` ship: each is real content read
  # through `:code.priv_dir/1` at runtime — the Chelekom bundle the UI-kit installer reads, the
  # pictures `MishkaCmsCore.Dev.SeedMedia` puts in a seeded media library, and the fonts
  # `MishkaCmsCore.Runtime.ShareCard` draws with — and `lib` carries the code that reads them, so
  # leaving any out ships half of a working thing. The rest of `priv` does NOT —
  # `priv/repo/migrations` and `priv/resource_snapshots` are generated by `mix ash.codegen` for the
  # standalone test database and describe tables a host owns. `config` and `test` are absent because
  # they exist only to run the suite on its own.
  defp package do
    [
      licenses: ["Apache-2.0"],
      files:
        ~w(lib priv/cms_ui_kits priv/dev_seed_media priv/share_card .formatter.exs mix.exs LICENSE README*)
    ]
  end

  # Run "mix help compile.app" to learn about applications.
  def application do
    [
      extra_applications: [:logger],
      mod: {MishkaCmsCore.Application, []}
    ]
  end

  # Run "mix help deps" to learn about dependencies.
  defp deps do
    [
      {:decimal, "~> 3.2", override: true},
      {:bcrypt_elixir, "~> 3.3"},
      {:sourceror, "~> 1.12", only: [:dev, :test]},
      {:open_api_spex, "~> 3.22"},
      {:ash_paper_trail, "~> 0.7"},
      {:ash_archival, "~> 2.0"},
      {:ash_authentication_phoenix, "~> 3.0.0-rc.11"},
      {:ash_authentication, "~> 5.0.0-rc.14"},
      {:eqrcode, "~> 0.2"},
      {:ash_postgres, "~> 2.13"},
      {:ash_json_api, "~> 1.7"},
      {:ash_phoenix, "~> 2.3"},
      {:ash_rate_limiter, "~> 2.0"},
      {:hammer, "~> 7.5"},
      {:remote_ip, "~> 1.2"},
      {:ash, "~> 3.33"},
      # {:ash, github: "ash-project/ash", branch: "main", override: true},
      {:igniter, "~> 0.8", only: [:dev, :test]},
      {:oban, "~> 2.24"},
      # `Phoenix.LiveViewTest` parses rendered markup with this. Test-only: it is never a burden on
      # anything that depends on this library.
      {:lazy_html, "~> 0.1", only: :test},
      # The editor's Heroicons catalogue (`Icons.Heroicons`) reads these SVGs at compile time. A host
      # brings its own copy, so this one serves only work on this library alone.
      {:heroicons,
       github: "tailwindlabs/heroicons",
       tag: "v2.2.0",
       sparse: "optimized",
       app: false,
       compile: false,
       depth: 1,
       only: [:dev, :test]},
      {:swoosh, "~> 1.28"},
      # The captcha providers' verify requests — see `MishkaCmsCore.Captcha.Provider.siteverify/2`.
      {:req, "~> 0.7"},
      {:ash_slug, "~> 0.2"},

      # Logger/Metrics Prod Stuff
      {:telemetry, "~> 1.4"},
      {:telemetry_metrics, "~> 1.2"},
      {:telemetry_poller, "~> 1.3"},

      # Runtime Asset Stuff
      {:esbuild, "~> 0.10"},
      {:tailwind, "~> 0.5"},
      {:igniter_js, "~> 0.5"},
      {:ex_brotli, "~> 0.6"},
      {:sitemapper, "~> 0.10"},
      {:picosat_elixir, "~> 0.2"},
      {:mishka_installer, "~> 0.1"},
      {:guarded_struct, "~> 0.1"},
      # `MishkaCmsCore.PlainText` takes markup out of plain-text fields with it.
      {:html_sanitize_ex, "~> 1.5"},
